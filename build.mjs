/**
 * Build the browser half into the single classic script the harness serves.
 *
 * Two constraints come from the client module system and shape this file:
 *
 *  - a plugin bundle is ONE file whose only job is to register a factory —
 *    `window.__ModuleLoader__.load({ id, factory })` with a CommonJS-style
 *    factory — so the output is wrapped by hand rather than emitted directly;
 *  - the factory's `require` only answers platform seed words (`react`,
 *    `react/jsx-runtime`, `@deepseek-ai/cordis`, the client UI registries) or
 *    packages this plugin declared in `dsh.client.inject`. Everything else,
 *    ProseMirror and Milkdown included, must be inlined, which is why there is no
 *    code splitting here.
 *
 * There is also deliberately no CSS output: Milkdown's theme packages are not
 * used, and the editor's stylesheet is a string injected by `src/client/theme.js`
 * (see its header for why that beats a second fetched asset).
 */
import { build } from 'esbuild';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const scratch = join(root, 'build');
const bodyPath = join(scratch, 'client.body.cjs');
const outPath = join(root, 'lib', 'client.js');

mkdirSync(scratch, { recursive: true });
mkdirSync(dirname(outPath), { recursive: true });

const result = await build({
  absWorkingDir: root,
  entryPoints: [join(root, 'src', 'client', 'index.js')],
  outfile: bodyPath,
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome122'],
  jsx: 'automatic',
  // Platform seed words stay external; the harness answers them from its frozen
  // module table when the factory materializes.
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  legalComments: 'none',
  sourcemap: false,
  minify: false,
  metafile: true,
  logLevel: 'warning',
  define: {
    // ProseMirror and remark both test this; a browser bundle is always "production".
    'process.env.NODE_ENV': '"production"',
  },
});

const body = readFileSync(bodyPath, 'utf8');
const wrapped = [
  '// Generated by build.mjs — do not edit. Source: src/client/.',
  'window.__ModuleLoader__.load({',
  `\tid: ${JSON.stringify(pkg.name)},`,
  '\tfactory: (require) => {',
  '\t\tvar module = { exports: {} };',
  '\t\tvar exports = module.exports;',
  body,
  '\t\treturn module.exports;',
  '\t}',
  '});',
  '',
].join('\n');

writeFileSync(outPath, wrapped, 'utf8');
rmSync(scratch, { recursive: true, force: true });

const bytes = Buffer.byteLength(wrapped);
const inputs = Object.entries(result.metafile.outputs)
  .flatMap(([, output]) => Object.keys(output.inputs))
  .filter((input) => input.includes('node_modules'))
  .map((input) => input.split('node_modules/').pop().split('/').slice(0, 2).join('/'));
console.log(`lib/client.js  ${(bytes / 1024).toFixed(1)} KB  (${new Set(inputs).size} bundled packages)`);
